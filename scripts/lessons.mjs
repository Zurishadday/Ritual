#!/usr/bin/env node
// Reads, checks and indexes the lessons in lessons/<language>/<group>.md.
// A lesson is a `### <id>. <title>` block with five bold parts (in Spanish: La idea, Ejemplo, Pregunta
// detectora, Señal de alarma, Qué hacer) and, only in the original Spanish, a data line in backticks:
// `origin: field` (or `lab · model · YYYY-MM`, or `proposal` with `source: ...`), and optionally
// `groups: other-group` and `packages: web`. Core ids are numbers from 1 on, with no gaps; those of a package
// carry a prefix (WEB-1). They are never renumbered or deleted: the redundant one only says «Fusionada en la N.»
// (or «Merged into N.»).
// The index (README.md of each language) is generated from the files: do not edit it by hand.
// Usage: node scripts/lessons.mjs --check      checks all languages and that each index is up to date
//        node scripts/lessons.mjs --index      regenerates the indexes
//        node scripts/lessons.mjs --selftest   calibrates the checker: cases that must fail and one that must pass
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

export const ROOT = path.resolve(import.meta.dirname, "..");
export const ORIGINAL = "es";
export const ORIGINS = ["field", "lab", "proposal"];
// Fixed order of the core groups in the index; packages come after, by name.
export const GROUPS = ["writing-and-docs", "numbers-and-data", "tests-and-checks", "scripts-and-files", "interface-and-design", "console-and-tools", "git-and-process"];
export const PARTS = {
  es: ["La idea", "Ejemplo", "Pregunta detectora", "Señal de alarma", "Qué hacer"],
  en: ["The idea", "Example", "Detector question", "Warning sign", "What to do"],
};
const MERGED = /^(?:Fusionada en la|Merged into) (\S+?)\.?$/m;
const REFERENCE = /\b(?:ver(?: también)? la|lecci[oó]n|(?:see )?lesson) (\d+)\b/gi;

/** Reads a group file and returns its lessons. */
export function readGroupFile(path, group) {
  const text = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
  const title = text.match(/^# (.+)$/m)?.[1] ?? null;
  const lessons = [];
  const blocks = text.split(/^(?=### )/m);
  let line = 1;
  for (const block of blocks) {
    const head = block.match(/^### (\S+)\. (.+)$/m);
    if (head) {
      const body = block.slice(head[0].length);
      const data = {};
      for (const m of body.matchAll(/`(\w+): ([^`]+)`/g)) data[m[1]] = m[2].trim();
      const parts = {};
      let current = null;
      for (const l of body.split("\n")) {
        const p = l.match(/^\*\*(.+?)\.\*\*\s*(.*)$/);
        if (p) { current = p[1]; parts[current] = p[2]; }
        else if (current && !/^`\w+: /.test(l)) parts[current] += "\n" + l;
      }
      for (const k in parts) parts[k] = parts[k].trim();
      lessons.push({ id: head[1], title: head[2].trim(), group, data, parts, merged: body.match(MERGED)?.[1] ?? null, text: body, line });
    }
    line += block.split("\n").length - 1;
  }
  return { title, lessons };
}

/** All lessons of a language, with the name of each group. @returns {{groups: Record<string,string>, lessons: object[]}} */
export function readLessons(language = ORIGINAL, root = ROOT) {
  const dir = path.join(root, "lessons", language);
  const groups = {};
  const lessons = [];
  for (const file of readdirSync(dir).filter((a) => a.endsWith(".md") && a !== "README.md").sort()) {
    const group = file.slice(0, -3);
    const { title, lessons: ls } = readGroupFile(path.join(dir, file), group);
    groups[group] = title;
    lessons.push(...ls.map((l) => ({ ...l, file: path.join("lessons", language, file) })));
  }
  return { groups, lessons };
}

function readConfigLanguage(project) {
  try { return JSON.parse(readFileSync(path.join(project, ".ritual", "config.json"), "utf8")).language ?? ORIGINAL; } catch { return ORIGINAL; }
}

const languagesIn = (dir) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name) : []);

const groupOrder = (g) => (GROUPS.includes(g) ? String(GROUPS.indexOf(g)).padStart(2, "0") : "9" + g);
const idOrder = (id) => (/^\d+$/.test(id) ? Number(id) : id);

export function generateIndex(language, root = ROOT) {
  const { groups, lessons } = readLessons(language, root);
  const lines = [language === "es" ? "# Índice de lecciones" : "# Index of lessons", "", "<!-- Generated by scripts/lessons.mjs --index: do not edit by hand. -->", ""];
  for (const g of Object.keys(groups).sort((a, b) => groupOrder(a).localeCompare(groupOrder(b)))) {
    lines.push(`## ${groups[g] ?? g}`, "");
    for (const l of lessons.filter((l) => l.group === g).sort((a, b) => (idOrder(a.id) > idOrder(b.id) ? 1 : -1)))
      lines.push(`- **${l.id}.** [${l.title}](${g}.md#${l.id.toLowerCase()}-${slug(l.title)})${l.merged ? (language === "es" ? ` (fusionada en la ${l.merged})` : ` (merged into ${l.merged})`) : ""}`);
    lines.push("");
  }
  return lines.join("\n");
}

const slug = (title) => title.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** @returns {{file: string, line: number, message: string}[]} */
export function check(root = ROOT) {
  const findings = [];
  const dir = path.join(root, "lessons");
  const languages = languagesIn(dir);
  if (!languages.includes(ORIGINAL)) return [{ file: "lessons", line: 0, message: `missing the original lessons/${ORIGINAL}/` }];
  const original = readLessons(ORIGINAL, root);
  const originalIds = new Set(original.lessons.map((l) => l.id));

  for (const language of languages) {
    const parts = PARTS[language];
    if (!parts) { findings.push({ file: `lessons/${language}`, line: 0, message: `no known names for the five parts in «${language}»: add them to PARTS` }); continue; }
    const { groups, lessons } = language === ORIGINAL ? original : readLessons(language, root);
    const bad = (l, message) => findings.push({ file: l.file, line: l.line, message: `${l.id}: ${message}` });
    for (const [g, title] of Object.entries(groups)) if (!title) findings.push({ file: `lessons/${language}/${g}.md`, line: 1, message: "the file has no title (# ...)" });

    const seen = new Map();
    for (const l of lessons) {
      if (!/^(\d+|[A-Z]+-\d+)$/.test(l.id)) bad(l, "the id must be a number (core) or PREFIX-number (package)");
      if (seen.has(l.id)) bad(l, `duplicate id, already in ${seen.get(l.id)}`);
      seen.set(l.id, l.file);
      if (l.merged) {
        if (!originalIds.has(l.merged)) bad(l, `merged into ${l.merged}, which does not exist`);
        if (Object.keys(l.parts).length) bad(l, "a merged lesson has no parts, only its merged line («Fusionada en la N.» / «Merged into N.»)");
        continue;
      }
      for (const p of parts) if (!l.parts[p]) bad(l, `missing part «${p}»`);
      if (language === ORIGINAL) {
        const [origin, model, date] = (l.data.origin ?? "").split("·").map((s) => s.trim());
        if (!ORIGINS.includes(origin)) bad(l, `unknown origin «${l.data.origin ?? ""}», must be one of: ${ORIGINS.join(", ")}`);
        if (origin === "lab" && !(model && /^\d{4}-\d{2}$/.test(date ?? ""))) bad(l, "a lab lesson needs model and date: `origin: lab · sonnet · 2026-10`");
        if (origin === "proposal" && !l.data.source) bad(l, "a proposal needs `source: ...`");
        for (const g of (l.data.groups ?? "").split(",").map((s) => s.trim()).filter(Boolean)) if (!(g in groups)) bad(l, `group «${g}» does not exist`);
        for (const m of `${l.title}\n${l.text}`.matchAll(REFERENCE)) if (!originalIds.has(m[1])) bad(l, `cites a lesson that does not exist (${m[1]})`);
      } else if (!originalIds.has(l.id)) bad(l, `does not exist in the original (${ORIGINAL})`);
    }
    if (language === ORIGINAL) {
      const numbers = lessons.map((l) => Number(l.id)).filter(Number.isInteger).sort((a, b) => a - b);
      for (let n = 1; n <= (numbers.at(-1) ?? 0); n++) if (!numbers.includes(n)) findings.push({ file: `lessons/${language}`, line: 0, message: `gap in numbers: lesson ${n} is missing` });
    } else {
      for (const id of originalIds) if (!seen.has(id)) findings.push({ file: `lessons/${language}`, line: 0, message: `missing translation of ${id}` });
    }
    const indexFile = path.join(dir, language, "README.md");
    const current = existsSync(indexFile) ? readFileSync(indexFile, "utf8").replace(/\r\n/g, "\n") : "";
    if (current.trim() !== generateIndex(language, root).trim()) findings.push({ file: `lessons/${language}/README.md`, line: 0, message: "index out of date: run `node scripts/lessons.mjs --index`" });
  }
  return findings;
}

/** The lessons of a project (.ritual/lessons/<group>.md): same format, prefixed ids, no index. */
export function checkProject(project, language = ORIGINAL) {
  const findings = [];
  const dir = path.join(project, ".ritual", "lessons");
  if (!existsSync(dir)) return [{ file: ".ritual/lessons", line: 0, message: "does not exist: run /ritual to start" }];
  const parts = PARTS[language] ?? PARTS[ORIGINAL];
  const seen = new Set();
  for (const file of readdirSync(dir).filter((a) => a.endsWith(".md")).sort()) {
    const group = file.slice(0, -3);
    const rel = `.ritual/lessons/${file}`;
    if (!GROUPS.includes(group)) { findings.push({ file: rel, line: 1, message: `the file must be named after a group: ${GROUPS.join(", ")}` }); continue; }
    for (const l of readGroupFile(path.join(dir, file), group).lessons) {
      const bad = (m) => findings.push({ file: rel, line: l.line, message: `${l.id}: ${m}` });
      if (!/^[A-Z]+-\d+$/.test(l.id)) bad("a project lesson needs a prefix and number (P-1)");
      if (seen.has(l.id)) bad("duplicate id");
      seen.add(l.id);
      if (l.merged) continue;
      for (const p of parts) if (!l.parts[p]) bad(`missing part «${p}»`);
      const origin = (l.data.origin ?? "").split("·")[0].trim();
      if (!ORIGINS.includes(origin)) bad(`unknown origin «${l.data.origin ?? ""}», must be one of: ${ORIGINS.join(", ")}`);
      for (const g of (l.data.groups ?? "").split(",").map((s) => s.trim()).filter(Boolean)) if (!GROUPS.includes(g)) bad(`group «${g}» does not exist`);
    }
  }
  return findings;
}

// Calibration: a case that must pass and, from it, cases that must fail with a specific message.
const LESSON = (id, title, extra = "`origin: field`") => `### ${id}. ${title}\n\n${extra}\n\n**La idea.** Algo.\n\n**Ejemplo.** Pasó esto.\n\n**Pregunta detectora.** ¿Y si no?\n\n**Señal de alarma.** «Seguro».\n\n**Qué hacer.** Medir.\n`;
const BASE = {
  "numbers-and-data.md": `# Cifras y datos\n\n${LESSON(1, "Uno")}\n${LESSON(2, "Dos (ver la 1)", "`origin: field` · `groups: git-and-process` · `packages: web`")}`,
  "git-and-process.md": `# Git y proceso\n\n### 3. Tres\n\nFusionada en la 1.\n\n${LESSON("WEB-1", "Uno de web", "`origin: proposal` · `source: https://example.org`")}\n${LESSON(4, "Cuatro", "`origin: lab · sonnet · 2026-10`")}`,
};
const CASES = [
  ["without the warning sign", (f) => ({ ...f, "numbers-and-data.md": f["numbers-and-data.md"].replace("**Señal de alarma.** «Seguro».\n", "") }), "missing part «Señal de alarma»"],
  ["duplicate id", (f) => ({ ...f, "git-and-process.md": f["git-and-process.md"] + "\n" + LESSON(1, "Otra uno") }), "duplicate id"],
  ["gap in numbers", (f) => ({ ...f, "git-and-process.md": f["git-and-process.md"].replace("### 4. ", "### 6. ") }), "gap in numbers: lesson 4"],
  ["cites a lesson that does not exist", (f) => ({ ...f, "numbers-and-data.md": f["numbers-and-data.md"].replace("(ver la 1)", "(ver la 9)") }), "cites a lesson that does not exist (9)"],
  ["invented origin", (f) => ({ ...f, "numbers-and-data.md": f["numbers-and-data.md"].replace("`origin: field`\n", "`origin: rumor`\n") }), "unknown origin «rumor»"],
  ["lab without date", (f) => ({ ...f, "git-and-process.md": f["git-and-process.md"].replace(" · sonnet · 2026-10", "") }), "model and date"],
  ["proposal without source", (f) => ({ ...f, "git-and-process.md": f["git-and-process.md"].replace(" · `source: https://example.org`", "") }), "needs `source"],
  ["group that does not exist", (f) => ({ ...f, "numbers-and-data.md": f["numbers-and-data.md"].replace("groups: git-and-process", "groups: cocina") }), "group «cocina» does not exist"],
  ["merged into a lesson that does not exist", (f) => ({ ...f, "git-and-process.md": f["git-and-process.md"].replace("Fusionada en la 1.", "Fusionada en la 8.") }), "merged into 8"],
  ["index out of date", (f) => ({ ...f, "README.md": "# Índice de lecciones\n" }), "index out of date"],
  ["incomplete translation", (f) => ({ ...f, "../en/numbers-and-data.md": "# Figures and data\n\n" + LESSON(1, "One").replace("La idea", "The idea").replace("Ejemplo", "Example").replace("Pregunta detectora", "Detector question").replace("Señal de alarma", "Warning sign").replace("Qué hacer", "What to do") }), "missing translation of 2"],
];

function assemble(files) {
  const tmp = mkdtempSync(path.join(os.tmpdir(), "lessons-"));
  const dir = path.join(tmp, "lessons", ORIGINAL);
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(dir, name);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  if (!("README.md" in files)) writeFileSync(path.join(dir, "README.md"), generateIndex(ORIGINAL, tmp));
  if (files["../en/numbers-and-data.md"]) writeFileSync(path.join(tmp, "lessons", "en", "README.md"), generateIndex("en", tmp));
  return tmp;
}

export function selftest() {
  const failures = [];
  const run = (files) => { const tmp = assemble(files); try { return check(tmp); } finally { rmSync(tmp, { recursive: true, force: true }); } };
  const base = run(BASE);
  if (base.length) failures.push(`the case that must pass has ${base.length} finding(s):\n` + base.map((h) => `    ${h.file}:${h.line} ${h.message}`).join("\n"));
  for (const [name, breakIt, expected] of CASES) {
    const h = run(breakIt(BASE));
    if (!h.some((x) => x.message.includes(expected))) failures.push(`«${name}» should fail with «${expected}» and gave: ${h.map((x) => x.message).join(" | ") || "nothing"}`);
  }
  // Project lessons: the good case passes; a file with an invented group name and an id without prefix fail.
  const project = mkdtempSync(path.join(os.tmpdir(), "lessons-project-"));
  try {
    mkdirSync(path.join(project, ".ritual", "lessons"), { recursive: true });
    writeFileSync(path.join(project, ".ritual", "lessons", "console-and-tools.md"), `# Consola\n\n${LESSON("P-1", "Propia", "`origin: field` · `refines: 27`")}`);
    const good = checkProject(project);
    if (good.length) failures.push(`the good project lessons gave: ${good.map((x) => x.message).join(" | ")}`);
    writeFileSync(path.join(project, ".ritual", "lessons", "cocina.md"), `# Cocina\n\n${LESSON("2", "Sin prefijo")}`);
    const bad = checkProject(project).map((x) => x.message).join(" | ");
    if (!bad.includes("must be named after a group")) failures.push(`a file with an invented group name should fail and gave: ${bad || "nothing"}`);
    writeFileSync(path.join(project, ".ritual", "lessons", "git-and-process.md"), `# Git\n\n${LESSON("2", "Sin prefijo")}`);
    if (!checkProject(project).some((x) => x.message.includes("prefix"))) failures.push("an id without prefix in a project lesson should fail");
  } finally { rmSync(project, { recursive: true, force: true }); }
  for (const m of failures) console.error(`✕ ${m}`);
  return failures.length;
}

if (import.meta.main) {
  if (process.argv.includes("--selftest")) {
    const failures = selftest();
    console.log(failures ? `${failures} case(s) failed` : `✓ calibrated: passes the good case and catches all ${CASES.length} bad cases`);
    process.exit(failures ? 1 : 0);
  }
  if (process.argv.includes("--index")) {
    for (const language of languagesIn(path.join(ROOT, "lessons"))) {
      writeFileSync(path.join(ROOT, "lessons", language, "README.md"), generateIndex(language));
      console.log(`✓ lessons/${language}/README.md`);
    }
    process.exit(0);
  }
  const i = process.argv.indexOf("--project");
  if (i >= 0) {
    const project = path.resolve(process.argv[i + 1] && !process.argv[i + 1].startsWith("--") ? process.argv[i + 1] : process.env.CLAUDE_PROJECT_DIR ?? process.cwd());
    const language = readConfigLanguage(project);
    const h = checkProject(project, language);
    for (const x of h) console.log(`${x.file}:${x.line}  ${x.message}`);
    console.log(h.length ? `✕ ${h.length} problem(s) in the project's lessons` : "✓ project lessons are well formed");
    process.exit(h.length ? 1 : 0);
  }
  const h = check();
  for (const x of h) console.log(`${x.file}:${x.line}  ${x.message}`);
  console.log(h.length ? `✕ ${h.length} problem(s) in the lessons` : `✓ ${readLessons().lessons.length} lessons are well formed, indexes up to date`);
  process.exit(h.length ? 1 : 0);
}
